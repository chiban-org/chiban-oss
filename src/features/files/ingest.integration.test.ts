import { randomUUID } from 'node:crypto'
import { eq } from 'drizzle-orm'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { files } from '@/db/schema'
import { blobKey, ingestTempObject, sha256Hex, storeGeneratedBytes } from '@/features/files/ingest'
import type { ObjectStore } from '@/features/storage/objectStore'
import { makeTestDb, type TestDb } from '@/test/db'
import { makeTestStore } from '@/test/objectStore'

const PDF = new TextEncoder().encode('%PDF-1.4\nbody one\n')

let t: TestDb
let store: ObjectStore
const signal = () => AbortSignal.timeout(20_000)

beforeEach(async () => {
  t = await makeTestDb()
  store = (await makeTestStore()).store
})

afterEach(async () => {
  await t.drop()
})

async function stage(bytes: Uint8Array): Promise<string> {
  const key = `uploads/tmp/${randomUUID()}`
  await store.putBytes(key, bytes, 'application/octet-stream', signal())
  return key
}

describe('ingestTempObject', () => {
  it('ingest stores the object under its hash and inserts one files row', async () => {
    const tempKey = await stage(PDF)
    const result = await ingestTempObject(
      t.db,
      store,
      { tempKey, declaredType: 'application/pdf', declaredSize: PDF.length },
      signal(),
    )
    expect(result.ok).toBe(true)
    const sha = sha256Hex(PDF)
    expect(result).toEqual({ ok: true, value: { sha256: sha, created: true } })
    const rows = await t.db.select().from(files)
    expect(rows).toHaveLength(1)
    expect(rows[0]?.storageKey).toBe(blobKey(sha))
    expect(blobKey(sha)).toBe(`blobs/sha256/${sha.slice(0, 2)}/${sha.slice(2, 4)}/${sha}`)
    expect((await store.head(blobKey(sha), signal())).ok).toBe(true)
    expect((await store.head(tempKey, signal())).ok).toBe(false)
  })

  it('ingesting identical bytes twice keeps one row and one object and reports created false', async () => {
    const input = (tempKey: string) => ({
      tempKey,
      declaredType: 'application/pdf' as const,
      declaredSize: PDF.length,
    })
    const first = await ingestTempObject(t.db, store, input(await stage(PDF)), signal())
    const second = await ingestTempObject(t.db, store, input(await stage(PDF)), signal())
    expect(first.ok && first.value.created).toBe(true)
    expect(second.ok && second.value.created).toBe(false)
    expect(await t.db.select().from(files)).toHaveLength(1)
  })

  it('size mismatch deletes the temp object', async () => {
    const tempKey = await stage(PDF)
    const result = await ingestTempObject(
      t.db,
      store,
      { tempKey, declaredType: 'application/pdf', declaredSize: PDF.length + 1 },
      signal(),
    )
    expect(result).toEqual({ ok: false, error: 'size_mismatch' })
    expect((await store.head(tempKey, signal())).ok).toBe(false)
    expect(await t.db.select().from(files)).toHaveLength(0)
  })

  it('type mismatch deletes the temp object', async () => {
    const png = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 1, 2])
    const tempKey = await stage(png)
    const result = await ingestTempObject(
      t.db,
      store,
      { tempKey, declaredType: 'application/pdf', declaredSize: png.length },
      signal(),
    )
    expect(result).toEqual({ ok: false, error: 'type_mismatch' })
    expect((await store.head(tempKey, signal())).ok).toBe(false)
  })

  it('a missing temp object is not_found', async () => {
    const result = await ingestTempObject(
      t.db,
      store,
      { tempKey: 'uploads/tmp/none', declaredType: 'application/pdf', declaredSize: 4 },
      signal(),
    )
    expect(result).toEqual({ ok: false, error: 'not_found' })
  })
})

describe('storeGeneratedBytes', () => {
  it('generated bytes are stored once by hash', async () => {
    const a = await storeGeneratedBytes(t.db, store, PDF, 'application/pdf', signal())
    const b = await storeGeneratedBytes(t.db, store, PDF, 'application/pdf', signal())
    expect(a.sha256).toBe(b.sha256)
    const rows = await t.db.select().from(files).where(eq(files.sha256, a.sha256))
    expect(rows).toHaveLength(1)
  })
})
